import type { SqlFragment } from './sql'

export type ColumnKind =
  | 'uuid'
  | 'text'
  | 'varchar'
  | 'integer'
  | 'bigint'
  | 'numeric'
  | 'boolean'
  | 'date'
  | 'timestamp'
  | 'jsonb'
  | 'char'

export type ColumnDef = {
  kind: ColumnKind
  sqlType: string
  nullable: boolean
  primary?: boolean
  unique?: boolean
  /** A value the app generates on insert (UUIDv7 ids, short codes, timestamps). */
  generate?: () => unknown
  /** SQL default (for migrations). */
  defaultSql?: string
  /** Static default used on insert when the value is missing. */
  defaultValue?: unknown
  oneOf?: readonly string[]
  references?: { table: () => { name: string }; column: string; onDelete?: string }
  check?: SqlFragment<unknown>
  /** Set on update automatically (updatedAt). */
  touch?: boolean
}

/**
 * A column. `T` is its TypeScript value type; `N` whether it accepts null; `D` whether inserts may omit it
 * (it has a default or is generated).
 */
export class Column<T, N extends boolean = false, D extends boolean = false> {
  declare readonly _type: T
  declare readonly _nullable: N
  declare readonly _hasDefault: D

  constructor(readonly def: ColumnDef) {}

  private with<T2 = T, N2 extends boolean = N, D2 extends boolean = D>(patch: Partial<ColumnDef>): Column<T2, N2, D2> {
    return new Column<T2, N2, D2>({ ...this.def, ...patch })
  }

  /** Columns are NOT NULL unless marked nullable. */
  nullable(): Column<T, true, true> {
    return this.with<T, true, true>({ nullable: true })
  }
  /** Default used on insert when the value is missing (also written into migrations). */
  default(value: T): Column<T, N, true> {
    return this.with<T, N, true>({ defaultValue: value })
  }
  /** SQL default, e.g. `defaultSql('now()')`, for migrations; inserts may omit the column. */
  defaultSql(expression: string): Column<T, N, true> {
    return this.with<T, N, true>({ defaultSql: expression })
  }
  unique(): this {
    return this.with({ unique: true }) as this
  }
  references(
    table: () => { name: string },
    options: { column?: string; onDelete?: 'cascade' | 'restrict' | 'set null' } = {},
  ): this {
    return this.with({ references: { table, column: options.column ?? 'id', onDelete: options.onDelete } }) as this
  }
  check(expression: SqlFragment<unknown>): this {
    return this.with({ check: expression }) as this
  }
}

/** A text column restricted to values: typed as the union and checked by a CHECK constraint. */
export class TextColumn<T extends string = string, N extends boolean = false, D extends boolean = false> extends Column<
  T,
  N,
  D
> {
  oneOf<const V extends readonly string[]>(values: V): TextColumn<V[number], N, D> {
    return new TextColumn<V[number], N, D>({ ...this.def, oneOf: values })
  }
  override nullable(): TextColumn<T, true, true> {
    return new TextColumn<T, true, true>({ ...this.def, nullable: true })
  }
  override default(value: T): TextColumn<T, N, true> {
    return new TextColumn<T, N, true>({ ...this.def, defaultValue: value })
  }
}

const col = <T>(kind: ColumnKind, sqlType: string, extra: Partial<ColumnDef> = {}) =>
  new Column<T>({ kind, sqlType, nullable: false, ...extra })

/** Primary key: UUIDv7 generated by the app (ids exist before insert; good index locality). */
export const id = () =>
  new Column<string, false, true>({
    kind: 'uuid',
    sqlType: 'uuid',
    nullable: false,
    primary: true,
    generate: () => Bun.randomUUIDv7(),
  })
export const uuid = () => col<string>('uuid', 'uuid')
export const text = () => new TextColumn<string>({ kind: 'text', sqlType: 'text', nullable: false })
export const varchar = (length: number) =>
  new TextColumn<string>({ kind: 'varchar', sqlType: `varchar(${length})`, nullable: false })
export const integer = () => col<number>('integer', 'integer')
export const bigint = () => col<bigint>('bigint', 'bigint')
/** Exact decimal, returned as a string (`'12.50'`). */
export const numeric = (precision: number, scale: number) => col<string>('numeric', `numeric(${precision},${scale})`)
export const boolean = () => col<boolean>('boolean', 'boolean')
/** A calendar date, as `'YYYY-MM-DD'`. */
export const date = () => col<string>('date', 'date')
/** An instant, `timestamptz` (stored in UTC), as a `Date`. */
export const timestamp = () => col<Date>('timestamp', 'timestamptz')
export const jsonb = <T>() => col<T>('jsonb', 'jsonb')
/** Money in minor units. */
export const amount = () => col<bigint>('bigint', 'bigint')
/** ISO 4217 code. */
export const currency = () => new TextColumn<string>({ kind: 'char', sqlType: 'char(3)', nullable: false })
/** Translated content: `{ fr, en, it }` as jsonb. */
export const translated = () => col<Partial<Record<string, string>>>('jsonb', 'jsonb')

const CROCKFORD = '0123456789ABCDEFGHJKMNPQRSTVWXYZ'
/** A short public reference, generated on insert: `shortCode('ALB')` → `ALB-7K2Q9F`. Unique. */
export const shortCode = (prefix: string, length = 6) =>
  new Column<string, false, true>({
    kind: 'text',
    sqlType: 'text',
    nullable: false,
    unique: true,
    generate: () => {
      const bytes = crypto.getRandomValues(new Uint8Array(length))
      return `${prefix}-${[...bytes].map((b) => CROCKFORD[b % 32]).join('')}`
    },
  })

/** `createdAt` and `updatedAt` (timestamptz), set by the app; `updatedAt` is refreshed on every update. */
export const timestamps = () => ({
  createdAt: new Column<Date, false, true>({
    kind: 'timestamp',
    sqlType: 'timestamptz',
    nullable: false,
    defaultSql: 'now()',
    generate: () => new Date(),
  }),
  updatedAt: new Column<Date, false, true>({
    kind: 'timestamp',
    sqlType: 'timestamptz',
    nullable: false,
    defaultSql: 'now()',
    generate: () => new Date(),
    touch: true,
  }),
})

/** `deletedAt` (nullable timestamptz): repositories soft-delete and hide deleted rows. */
export const softDeletes = () => ({ deletedAt: timestamp().nullable() })

