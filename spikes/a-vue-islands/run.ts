/**
 * Spike (a) runner: `bun run.ts` from spikes/a-vue-islands.
 *  1. builds the browser bundle (Bun.build + .vue plugin, one chunk per island)
 *  2. renders pages on the server with the runtime .vue loader
 *  3. loads them in headless Chrome and checks hydration
 *  4. checks edge cases (slots on islands, whole-props mapped types) and measures SSR speed
 */
import { mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { compileSfc } from './src/sfc'

const ROOT = import.meta.dir
const results: Record<string, unknown> = {}
const check = (name: string, ok: boolean, detail?: unknown) => {
  ;(results.checks ??= []) as unknown[]
  ;(results.checks as unknown[]).push({ check: name, ok, ...(detail === undefined ? {} : { detail }) })
}

// ── 1. browser bundle ────────────────────────────────────────────────────────────────────────────
const islandFiles = readdirSync(join(ROOT, 'components')).filter((f) => f.endsWith('.vue') && f !== 'whole-mapped-props.vue')
writeFileSync(
  join(ROOT, 'src/islands.generated.ts'),
  `// generated by run.ts\nexport const islands: Record<string, () => Promise<{ default: object }>> = {\n${islandFiles
    .map((f) => `  'components/${f.replace('.vue', '')}': () => import('../components/${f}'),`)
    .join('\n')}\n}\n`,
)
rmSync(join(ROOT, 'build'), { recursive: true, force: true })
const t0 = performance.now()
const build = await Bun.build({
  entrypoints: [join(ROOT, 'src/client.ts')],
  outdir: join(ROOT, 'build'),
  target: 'browser',
  format: 'esm',
  splitting: true,
  minify: true,
  naming: { entry: '[name].[ext]', chunk: '[name]-[hash].[ext]' },
  define: {
    'process.env.NODE_ENV': '"development"', // keep Vue's hydration-mismatch warnings
    __VUE_OPTIONS_API__: 'true',
    __VUE_PROD_DEVTOOLS__: 'false',
    __VUE_PROD_HYDRATION_MISMATCH_DETAILS__: 'true',
  },
  plugins: [
    {
      name: 'cslug-vue-client',
      setup(b) {
        b.onLoad({ filter: /\.vue$/ }, ({ path }) => ({ contents: compileSfc(path, ROOT, false).code, loader: 'ts' }))
      },
    },
  ],
})
if (!build.success) {
  console.error(build.logs)
  process.exit(1)
}
results.clientBuild = {
  ms: Math.round(performance.now() - t0),
  outputs: build.outputs.map((o) => ({ file: o.path.slice(ROOT.length + 1), kb: +(o.size / 1024).toFixed(1) })),
}

// ── 2. server rendering ──────────────────────────────────────────────────────────────────────────
const { view, compileTimes } = await import('./src/server')
const Page = (await import('./views/page.vue')).default
const Static = (await import('./views/static.vue')).default
const days = [
  { id: 'd1', title: 'Antananarivo → Andasibe', date: new Date('2027-05-14T06:00:00Z'), priceMinor: 12000n },
  { id: 'd2', title: 'Andasibe → Antsirabe', date: new Date('2027-05-15T06:00:00Z'), priceMinor: 9500n },
]
const page = await view(Page, { title: 'Tana – Isalo', days })
const stat = await view(Static, { days })
check('server render: islands detected on the page', page.islands.length > 0, page.islands)
check('static page ships no JavaScript', !stat.html.includes('<script') && stat.islands.length === 0)
check('static page renders the component', stat.html.includes('Antananarivo → Andasibe'))
check(
  'server renders island props in serialized form (bigint → string, Date → ISO)',
  page.html.includes('&quot;priceMinor&quot;:&quot;12000&quot;') && page.html.includes('2027-05-14T06:00:00.000Z'),
)
check('scoped CSS emitted with data-v attribute', /\.day\[data-v-[0-9a-f]+\]/.test(page.html))

// ── 3. headless Chrome ───────────────────────────────────────────────────────────────────────────
const pages: Record<string, string> = { '/': page.html }
const server = Bun.serve({
  port: 0,
  async fetch(req) {
    const url = new URL(req.url)
    const html = pages[url.pathname]
    if (html) return new Response(html, { headers: { 'content-type': 'text/html' } })
    if (url.pathname.startsWith('/build/')) return new Response(Bun.file(join(ROOT, url.pathname)))
    return new Response('not found', { status: 404 })
  },
})

/** Load a page in headless Chrome; returns the DOM after JS ran and the console lines. */
async function inChrome(path: string) {
  const profile = mkdtempSync(join(tmpdir(), 'spike-a-chrome-'))
  // async spawn: spawnSync would block this process, and with it the Bun.serve answering Chrome's requests
  const proc = Bun.spawn(
    [
      'google-chrome',
      '--headless=new',
      '--disable-gpu',
      '--no-first-run',
      `--user-data-dir=${profile}`,
      '--enable-logging=stderr',
      '--v=0',
      '--window-size=1280,900',
      '--virtual-time-budget=5000',
      '--dump-dom',
      `http://localhost:${server.port}${path}`,
    ],
    { stdout: 'pipe', stderr: 'pipe', timeout: 60_000 },
  )
  const [out, err] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text()])
  await proc.exited
  rmSync(profile, { recursive: true, force: true })
  return { dom: out, console: err.split('\n').filter((l) => l.includes('CONSOLE')) }
}

const Mismatch = (await import('./views/mismatch-page.vue')).default
pages['/mismatch'] = (await view(Mismatch, {})).html
const control = await inChrome('/mismatch')
check(
  'negative control: a deliberate server/browser difference IS reported as a hydration mismatch',
  control.console.some((l) => /hydration/i.test(l)),
  control.console.map((l) => l.replace(/^.*CONSOLE\(\d+\)\]\s*/, '').slice(0, 160)).slice(0, 2),
)

const main = await inChrome('/')
server.stop(true)
const dom = main.dom
const consoleLines = main.console
results.browserConsole = consoleLines.map((l) => l.replace(/^.*CONSOLE\(\d+\)\]\s*/, '').slice(0, 300))

const counter = (label: string) => {
  const m = dom.match(new RegExp(`<button[^>]*data-label="${label}"[^>]*>(\\d+)</button>`))
  const tag = dom.match(new RegExp(`<button[^>]*data-label="${label}"[^>]*>`))?.[0] ?? ''
  return { value: m ? Number(m[1]) : null, hydrated: tag.includes('data-hydrated="true"') }
}
const load = counter('load')
const idle = counter('idle')
const media = counter('media')
const offscreen = counter('offscreen')
check('hydrate="load" island hydrated and reactive (3 → 4)', load.hydrated && load.value === 4, load)
check('hydrate="idle" island hydrated and reactive (10 → 11)', idle.hydrated && idle.value === 11, idle)
check('hydrate="media:…" island hydrated (20 → 21)', media.hydrated && media.value === 21, media)
check('hydrate="visible" island far below the fold did NOT hydrate', !offscreen.hydrated && offscreen.value === 100, offscreen)
const dayIslands = dom.match(/<li[^>]*class="day"[^>]*>/g) ?? []
check(
  'same component: 2 static copies stay static, the visible island hydrates',
  dayIslands.length === 3 && dayIslands.filter((t) => t.includes('data-hydrated="true"')).length === 1,
  dayIslands,
)
const mismatch = consoleLines.filter((l) => /hydration|mismatch/i.test(l))
check('no hydration mismatch warnings in the browser console', mismatch.length === 0, mismatch)
const errors = consoleLines.filter((l) => /error|uncaught/i.test(l))
check('no errors in the browser console', errors.length === 0, errors)

// ── 4. edge cases ────────────────────────────────────────────────────────────────────────────────
try {
  compileSfc(join(ROOT, 'views/slot-island.vue'), ROOT, true)
  check('slot content on an island is a compile error', false)
} catch (e) {
  check('slot content on an island is a compile error', /cannot receive slot content/.test(String(e)), String(e).slice(0, 160))
}
try {
  compileSfc(join(ROOT, 'components/whole-mapped-props.vue'), ROOT, true)
  results.wholePropsMappedType = 'compiles'
} catch (e) {
  results.wholePropsMappedType = `fails: ${String(e).split('\n')[0]?.slice(0, 200)}`
}

// ── 5. performance ───────────────────────────────────────────────────────────────────────────────
for (let i = 0; i < 50; i++) await view(Page, { title: 'warm', days })
const N = 1000
const t1 = performance.now()
for (let i = 0; i < N; i++) await view(Page, { title: `t${i}`, days })
const perRender = (performance.now() - t1) / N
results.ssr = {
  renders: N,
  msPerRender: +perRender.toFixed(3),
  rendersPerSecond: Math.round(1000 / perRender),
  pageBytes: page.html.length,
}
results.serverCompileMs = compileTimes.map((c) => ({ ...c, ms: +c.ms.toFixed(1) }))

console.log(JSON.stringify(results, null, 2))
const failed = (results.checks as { ok: boolean }[]).filter((c) => !c.ok).length
console.log(failed ? `\n✖ ${failed} check(s) failed` : '\n✔ all checks passed')
process.exit(failed ? 1 : 0)
